"""Generate ``AGENTS.md`` — the README that coding agents actually read.

AGENTS.md is a plain-Markdown convention stewarded by the Agentic AI Foundation under the
Linux Foundation, alongside MCP and goose. It is read natively by Codex, Cursor, Copilot's
coding agent, Gemini CLI, Aider, goose, opencode, Zed, Warp, VS Code, Devin, Windsurf,
Junie, Amp and others, and appears in 60k+ public repositories. There are no required
fields — an agent parses whatever Markdown you write.

That is exactly why generating it is worth doing. A workspace full of tested prompts is
invisible to a coding agent that does not know the prompts exist, what they take, or which
command runs them. Writing that down by hand goes stale the moment someone adds a file;
generating it from the workspace cannot.

**Why a compact index rather than the full bodies.** The published guidance is that the
nearest AGENTS.md wins and its contents enter the agent's context. Pasting every prompt
body in would spend the agent's context budget on material it did not ask for — the exact
failure progressive disclosure exists to prevent. So this emits the tier-1 index: id,
summary, inputs, and the command to fetch the rest.

**Why the commands are listed explicitly.** Per the AGENTS.md FAQ, agents will attempt to
run the checks they find here. ``assay test`` is offline, deterministic and exits non-zero
on failure, which makes it safe to hand an agent as a verification step.

The same content is emitted for ``CLAUDE.md``, because Claude Code reads that name rather
than AGENTS.md.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Iterable

#: Files that carry the same content under different names. AGENTS.md is the standard;
#: CLAUDE.md exists because Claude Code does not read AGENTS.md.
TARGETS = {
    "agents": "AGENTS.md",
    "claude": "CLAUDE.md",
}

#: Marker pair so a generated block can be refreshed inside a file a human also edits.
#: Regenerating replaces only what is between the markers — anything a person wrote
#: around them survives, which is what makes this safe to re-run.
BEGIN = "<!-- assay:begin — generated by `assay agents init`. Edits inside are overwritten. -->"
END = "<!-- assay:end -->"


@dataclass
class Section:
    heading: str
    body: str


def _describe(artifact: Any) -> dict:
    data = getattr(artifact, "data", {}) or {}
    kind = (
        "harness" if getattr(artifact, "is_harness", False)
        else "loop" if getattr(artifact, "is_loop", False)
        else getattr(artifact, "kind", "prompt")
    )
    try:
        variables = sorted(artifact.template_variables())
    except Exception:
        variables = []
    return {
        "id": artifact.id,
        "kind": kind,
        "summary": (data.get("summary") or data.get("description") or "").strip(),
        "variables": variables,
        "has_evals": bool(getattr(artifact, "evals", None)),
        "status": getattr(artifact, "status", "") or "",
    }


def _inventory_table(items: list[dict]) -> str:
    if not items:
        return "_No artifacts yet._"
    rows = ["| id | kind | inputs | tested | what it does |",
            "|:--|:--|:--|:--:|:--|"]
    for item in items:
        variables = ", ".join(f"`{v}`" for v in item["variables"]) or "—"
        summary = item["summary"] or "—"
        if len(summary) > 90:
            summary = summary[:87].rstrip() + "…"
        rows.append(
            f"| `{item['id']}` | {item['kind']} | {variables} | "
            f"{'yes' if item['has_evals'] else 'no'} | {summary} |"
        )
    return "\n".join(rows)


def generate(
    artifacts: Iterable[Any],
    *,
    workspace_name: str = "this workspace",
    prompts_dir: str = "prompts",
    include_generated_note: bool = True,
) -> str:
    """Build the generated block. Returns Markdown, not a file."""
    items = sorted((_describe(a) for a in artifacts), key=lambda d: d["id"])
    harnesses = [i for i in items if i["kind"] == "harness"]
    loops = [i for i in items if i["kind"] == "loop"]
    untested = [i["id"] for i in items if not i["has_evals"]]

    def _plural(n: int, one: str, many: str) -> str:
        return f"{n} {one if n == 1 else many}"

    extras = []
    if harnesses:
        extras.append(_plural(len(harnesses), "agent harness", "agent harnesses"))
    if loops:
        extras.append(_plural(len(loops), "verified loop", "verified loops"))
    _extra = f", including {' and '.join(extras)}" if extras else ""

    parts: list[str] = []

    parts.append(f"""## Prompts and agents in this repository

This repository uses [Assay](https://github.com/BaijayantaRoy/Assay) to keep prompts and
agents as files. Each one is a **PromptFile** — YAML frontmatter plus a Markdown body,
carrying its template, model binding, guardrails and **its own test cases**.

They live in `{prompts_dir}/`. There are {len(items)} of them{_extra}.

**Before writing a new prompt, check whether one already exists here.** Reusing a tested
artifact is nearly always better than writing an untested one inline.""")

    parts.append(f"""## What is available

{_inventory_table(items)}

Bodies are deliberately not reproduced here — they would spend your context budget on
material you did not ask for. Fetch one with `assay show <id>`.""")

    parts.append("""## Commands

All of these work offline against a deterministic `echo` provider, so they need no API key
and cost nothing to run.

```bash
assay ls                             # list every artifact with its id
assay show <id>                      # full source of one artifact
assay render <id> -v key=value       # fill the template, no model call
assay run <id> -v key=value          # execute against the bound model
assay test                           # run every embedded eval — exit 4 on failure
assay test <id>                      # just this one
assay lint                           # validate against the PromptFile spec
```

**`assay test` is the check to run after editing anything under the prompts directory.**
It exits non-zero on failure and needs no network.""")

    if harnesses:
        parts.append(f"""## Agent harnesses

{chr(10).join(f"- `{h['id']}` — {h['summary'] or 'no summary'}" for h in harnesses)}

A harness declares its own tools, budget, memory and controls, and every run produces a
**trajectory**: the record of what the agent actually did. Assertions check the path, not
just the final answer — an agent can reach the right result through a tool call it should
never have made.

```bash
assay run <harness-id> -v goal='...'   # run it, get the trajectory
assay redteam <harness-id>             # measure its injection defences
```""")

    parts.append("""## Editing rules

- **Do not paste prompt text into code.** Reference the artifact by id and render it, so
  there is one copy and it stays tested.
- **A new artifact needs at least one eval case.** An artifact with no evals passes every
  run by default, which is not the same as working.
- **Run `assay test` before finishing.** If it fails, fix the artifact rather than
  loosening the assertion.
- **Do not edit generated blocks** between the `assay:begin` and `assay:end` markers in
  this file; run `assay agents init` instead.""")

    if untested:
        shown = ", ".join(f"`{i}`" for i in untested[:8])
        more = f" and {len(untested) - 8} more" if len(untested) > 8 else ""
        parts.append(f"""## Known gaps

{len(untested)} artifact(s) carry no eval cases and are therefore unverified: {shown}{more}.

Treat their output with the same suspicion you would give untested code.""")

    body = "\n\n".join(parts)

    if include_generated_note:
        stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d")
        body += (
            f"\n\n<sub>Generated from {workspace_name} by `assay agents init` on {stamp}. "
            "Re-run after adding or removing artifacts.</sub>"
        )
    return body


def render_file(existing: str | None, generated: str) -> str:
    """Splice the generated block into an existing file, or create a new one.

    Only the region between the markers is replaced. Anything a human wrote above or
    below survives regeneration — without that, running this twice would silently destroy
    hand-written instructions, and nobody would run it twice.
    """
    block = f"{BEGIN}\n\n{generated}\n\n{END}"

    if not existing or not existing.strip():
        return f"# AGENTS.md\n\n{block}\n"

    if BEGIN in existing and END in existing:
        head, _, rest = existing.partition(BEGIN)
        _, _, tail = rest.partition(END)
        return f"{head}{block}{tail}"

    # An AGENTS.md that predates Assay: append rather than overwrite.
    return existing.rstrip() + f"\n\n{block}\n"


def write(
    root: Path,
    artifacts: Iterable[Any],
    *,
    targets: Iterable[str] = ("agents",),
    workspace_name: str = "this workspace",
    prompts_dir: str = "prompts",
) -> list[dict]:
    """Write the generated block into each requested target file."""
    generated = generate(
        list(artifacts), workspace_name=workspace_name, prompts_dir=prompts_dir
    )
    written = []
    for target in targets:
        filename = TARGETS.get(target, target)
        path = Path(root) / filename
        existing = path.read_text(encoding="utf-8") if path.exists() else None
        content = render_file(existing, generated)
        created = not path.exists()
        path.write_text(content, encoding="utf-8")
        written.append({
            "file": filename,
            "path": str(path),
            "created": created,
            "preserved_existing": bool(existing and BEGIN not in (existing or "")),
        })
    return written
